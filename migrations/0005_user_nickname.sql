-- 사용자가 직접 고른 닉네임.
--
-- 지금 `users.name`은 소셜 제공자가 준 이름이고, 로그인할 때마다 덮어쓰인다.
-- 사용자가 닉네임을 정하면 그 값이 덮이면 안 되므로, **직접 정했는지**를 기록한다.
--
-- 시각을 쓰는 이유는 두 가지를 한 열로 답하기 위해서다.
--   1. NULL이면 아직 제공자 이름 그대로다 → 로그인 시 덮어써도 된다
--   2. 값이 있으면 마지막으로 바꾼 때다 → 너무 잦은 변경을 막는 근거가 된다
--
-- 닉네임은 편집 기록 옆에 남는 이름이다. 바꾸면 지난 편집의 표시 이름도 함께 바뀌므로
-- (조회 시점에 users를 조인한다) 아무 때나 바꾸게 두면 사칭에 쓰인다.
ALTER TABLE users ADD COLUMN name_changed_at TEXT;
